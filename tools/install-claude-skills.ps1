function Link-Skill($from, $to) {
    if (Test-Path -LiteralPath $to) { return 'existe' }
    if (-not (Test-Path -LiteralPath (Join-Path $from 'SKILL.md'))) { return 'ausente' }
    New-Item -ItemType Junction -Path $to -Target $from | Out-Null
    return 'ok'
}

if ($Uninstall) {
    $n = 0
    Get-ChildItem -LiteralPath $dst -Directory -ErrorAction SilentlyContinue |
      Where-Object { $_.LinkType -eq 'Junction' -and "$($_.Target)" -like "$src*" } |
      ForEach-Object { [System.IO.Directory]::Delete($_.FullName); $n++ }
    Write-Host "Removidas $n junctions de $dst (originais em $src intactos)."
    return
}

New-Item -ItemType Directory -Force -Path $dst | Out-Null
$stats = @{ ok = 0; existe = 0; ausente = 0 }
$faltando = @()
foreach ($s in $skills) {
    $r = Link-Skill (Join-Path $src $s) (Join-Path $dst $s)
    $stats[$r]++
    if ($r -eq 'ausente') { $faltando += $s }
}
Write-Host "Global ($dst): $($stats.ok) ligadas, $($stats.existe) ja existiam, $($stats.ausente) nao encontradas."
if ($faltando) { Write-Host "Nao encontradas: $($faltando -join ', ')" }

# Skill local do projeto que faltava no .claude
$pSrc = Join-Path $projRoot '.agents\skills\gauntlet-loop'
$pDst = Join-Path $projRoot '.claude\skills\gauntlet-loop'
if (Test-Path -LiteralPath $pSrc) {
    New-Item -ItemType Directory -Force -Path (Split-Path $pDst) | Out-Null
    Write-Host "Projeto gauntlet-loop: $(Link-Skill $pSrc $pDst)"
}
Write-Host 'Pronto. Reinicie o Claude Code e confira com /skills.'
